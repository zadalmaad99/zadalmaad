export function normalizePhoneDigits(value) {
  const digits = (value || "").replace(/[^\d]/g, "");
  const dial = DIAL_CODES.find((d) => digits.startsWith(d));
  if (!dial) return digits.replace(/^0+/, "");
  const local = digits.slice(dial.length).replace(/^0+/, "");
  return `${dial}${local}`;
}
